export function speakText(text: string, lang: AppLanguage = 'en-IN', onEnd?: () => void) {
  if (typeof window === 'undefined' || !('speechSynthesis' in window)) {
    onEnd?.();
    return;
  }

  try {
    window.speechSynthesis.cancel();
    const cleanText = text.replace(/[*#_~`[\]()<>]/g, ' ').replace(/\s+/g, ' ').trim();
    if (!cleanText) {
      onEnd?.();
      return;
    }

    const utterance = new SpeechSynthesisUtterance(cleanText);
    utterance.lang = lang;
    utterance.rate = 0.95;
    utterance.pitch = 1.0;

    const voices = window.speechSynthesis.getVoices();
    const targetLang = lang.split('-')[0].toLowerCase();
    const voiceMatch = voices.find(
      (v) => v.lang.toLowerCase().startsWith(targetLang) || v.lang.toLowerCase().replace('_', '-').startsWith(targetLang)
    );
    if (voiceMatch) {
      utterance.voice = voiceMatch;
    }

    utterance.onend = () => onEnd?.();
    utterance.onerror = () => onEnd?.();

    window.speechSynthesis.speak(utterance);
  } catch {
    onEnd?.();
  }
}

export function stopSpeaking() {
  if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
    try {
      window.speechSynthesis.cancel();
    } catch {
      // ignore
    }
  }
}
